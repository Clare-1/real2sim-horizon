"""Fixed 300-rollout privileged-expert feasibility check for the full-H screen."""
from __future__ import annotations

import argparse
from collections import Counter
from dataclasses import asdict
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
import platform
import sys
import time


FAMILIES = ("pack", "sort", "stack")
HORIZONS = (2, 4, 6, 8, 10)
MODES = (("nominal", 0.0), ("perturbed", 0.15))
BANK = 77_000_000
N_PER = 10
WORKERS = 2


def require(ok, message):
    if not ok:
        raise ValueError(message)


def read_json(path):
    return json.loads(Path(path).read_text(encoding="utf-8"))


def file_hash(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def digest(value):
    return hashlib.sha256(json.dumps(value, sort_keys=True, ensure_ascii=False,
                                    allow_nan=False, separators=(",", ":")).encode()).hexdigest()


def utc_now():
    return datetime.now(timezone.utc).isoformat()


def plan_text(plan):
    return f"""# Independent expert feasibility addendum

This development diagnostic was specified before this investigator inspected any
full-H learned-policy outcomes. The main five-system screen was already running.
It is an addendum to ../PLAN.md, not a change to that protocol or a preregistered
confirmation study. No learned scores are read by this script.

Exactly 300 episodes: pack/sort/stack x H=2/4/6/8/10 x 10 tasks x nominal/perturbed.
The 150 task identities are generated by the main screen's frozen TaskStore and
eval_jobs, with final bank 77M and rollout_seed=task_seed+17. Every eval_jobs field
is retained except controller='expert'. The original privileged state expert uses
identity ReconModel, real=True, the same physical world, action limits, simulator,
scorer, and stopping defaults. Max steps remain H*180+60, done patience is 8,
expert noise is zero, and workers=2. Perturbed mode has slip=.15, displace=.15,
knock=.075, traj=target=0. No training, calibration, tuning, task replacement,
retry, early stopping based on scores, or additional evaluation is authorized.

All 300 results, including errors and failures, are retained. Full success is
unchanged log.success on the true final state; judged success and final predicate
progress are separate diagnostics. Summary denominators include all scheduled
episodes, with error and missing-progress counts explicit. Actual control/physics
steps, sum of worker rollout-loop seconds, and elapsed pool time are recorded.
Worker errors can make some actual cost unavailable; zero reported worker cost
does not imply zero work. Per-cell intermediate outcomes are saved as execution
proceeds. A STARTED marker prevents accidental repetition after interruption.

The script and frozen source, original manifest and main protocol, every task and
identity sidecar, full jobs and simulator/expert/scorer defaults are hashed or
recorded in definition.json. Task files are materialized only in this output.
Existing main-screen task artifacts are compared read-only when available.

Source experiment fingerprint: `{plan['source_experiment_fingerprint']}`
Expert definition fingerprint: `{plan['fingerprint']}`
Script SHA256: `{plan['script']['sha256']}`

This expert receives privileged simulator state. Success supports executability
only for these 150 sampled tasks and two sampled conditions; it is not an
observation-matched learned-policy baseline, proof that all failures are learning
failures, evidence of physical transfer, or evidence of agentic-learning benefit.
Expert failure does not prove impossibility. The confirmation bank is unused.
"""


def summarize(episodes):
    rows = []
    for family in FAMILIES:
        for H in HORIZONS:
            for mode, _ in MODES:
                group = [e for e in episodes if (e["family"], e["H"], e["mode"]) == (family, H, mode)]
                valid = [e for e in group if e["progress"] is not None]
                rows.append({"family": family, "H": H, "mode": mode, "episodes": len(group),
                             "successes": sum(e["success"] is True for e in group),
                             "success_rate": sum(e["success"] is True for e in group) / len(group),
                             "errors": sum(e["error"] is not None or e["success"] is None for e in group),
                             "progress_observed": len(valid),
                             "mean_final_progress": sum(e["progress"] for e in valid) / len(valid) if valid else None,
                             "mean_final_prefix": sum(e["first_unsatisfied_index"] for e in valid) / len(valid) if valid else None,
                             "control_steps": sum(e["steps"] or 0 for e in group),
                             "sim_steps": sum(e["sim_steps"] for e in group),
                             "worker_seconds": sum(e["worker_seconds"] for e in group)})
    return rows


def report_text(result):
    lines = ["# Full-H expert feasibility diagnostic", "",
             "Original privileged state expert; healthy/identity reconstruction; same frozen",
             "physical world, task artifacts, rollout seeds, stopping rules and scorer as the",
             "full-H learned screen. No training, calibration, tuning, or replaced tasks.", "",
             "| Family | H | Mode | Full success | Mean final progress | Control steps | Physics steps |",
             "|---|---:|---|---:|---:|---:|---:|"]
    for row in result["summary"]:
        progress = "unavailable" if row["mean_final_progress"] is None else f"{row['mean_final_progress']:.3f}"
        lines.append(f"| {row['family']} | {row['H']} | {row['mode']} | "
                     f"{row['successes']}/{row['episodes']} | {progress} | "
                     f"{row['control_steps']:,} | {row['sim_steps']:,} |")
    ledger = result["ledger"]
    lines.extend(["", f"Status: {result['status']}; worker errors: {ledger['worker_errors']}.",
                  f"Actual episodes: {ledger['episodes']}; control steps: {ledger['control_steps']:,}; "
                  f"physics steps: {ledger['sim_steps']:,}.",
                  f"Sum of worker rollout-loop time: {ledger['worker_seconds']:.3f} s; "
                  f"pool wall time including startup/shutdown: {ledger['pool_wall_seconds']:.3f} s.",
                  "Worker time excludes environment construction and is not elapsed time. This run",
                  "shared the machine with the main screen, so these costs are not a speed benchmark.",
                  "Any failed worker can have unreported cost; summary success denominators include",
                  "all scheduled episodes, while mean progress uses available logs with explicit counts.", "",
                  f"Read-only comparison found {result['main_task_comparison']['matched']} matching main-screen "
                  f"task artifacts and {result['main_task_comparison']['unavailable']} not yet available.",
                  "All 150 independent task/sidecar hashes, 300 job settings, source/script hashes,",
                  "expert/scorer defaults, per-episode final predicates, perturbation events and costs",
                  "are recorded in definition.json/results.json. Commanded actions are in actions.npz.", "",
                  "The addendum was fixed before this investigator viewed full-H learned outcomes;",
                  "the five-system screen was already underway. This is development evidence.",
                  "The expert receives privileged state. Success demonstrates sampled executability",
                  "only, not an observation-matched comparison, universal feasibility, a diagnosis of",
                  "every learned failure, physical transfer, or agentic-learning advantage.", ""])
    return "\n".join(lines)


def verify_saved(result, plan):
    require(result["definition_fingerprint"] == plan["fingerprint"], "Wrong result definition")
    require(result["record_sha256"] == digest({k: v for k, v in result.items() if k != "record_sha256"}),
            "Result checksum mismatch")
    require(file_hash(result["actions"]["path"]) == result["actions"]["sha256"], "Actions hash mismatch")
    expected = {(mode, family, H, BANK + fi * 100_000 + H * 1000 + i)
                for mode, _ in MODES for fi, family in enumerate(FAMILIES) for H in HORIZONS for i in range(N_PER)}
    actual = [(e["mode"], e["family"], e["H"], e["task_seed"]) for e in result["episodes"]]
    require(len(actual) == 300 and set(actual) == expected, "Result identity set mismatch")
    require(all(e["rollout_seed"] == e["task_seed"] + 17 for e in result["episodes"]), "Wrong rollout seed")
    require(result["summary"] == summarize(result["episodes"]), "Summary arithmetic mismatch")
    ledger = result["ledger"]
    for field, episode_field in (("control_steps", "steps"), ("sim_steps", "sim_steps"), ("worker_seconds", "worker_seconds")):
        require(ledger[field] == sum(e[episode_field] or 0 for e in result["episodes"]), f"Cost mismatch: {field}")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--plan-only", action="store_true")
    args = parser.parse_args()
    base = Path(__file__).resolve().parents[1]
    parent = base / "results/long_horizon_dev_20261028"
    source = parent / "fullH_dagger"
    out = parent / "fullH_expert"
    sys.dont_write_bytecode = True
    sys.path.insert(0, str(source / "source/src"))

    import mujoco
    import numpy as np
    import horizon.datagen.parallel as parallel
    from horizon.datagen.rollout import rollout
    from horizon.harness.artifacts import write_json
    from horizon.harness.experiment import TaskStore, eval_jobs, source_hashes
    from horizon.real2sim.recon_error import ReconModel
    from horizon.sim.mjcf import SimConfig
    from horizon.skills.expert import ExpertConfig
    from horizon.taskgraph.predicates import Tolerances

    require(Path(parallel.__file__).resolve().is_relative_to(source / "source/src"), "Wrong imported source")
    manifest = read_json(source / "experiment.json")
    require(manifest["fingerprint"] == digest({k: v for k, v in manifest.items() if k != "fingerprint"}),
            "Source manifest fingerprint mismatch")
    require(source_hashes() == manifest["source_sha256"], "Frozen source hashes differ")
    cfg = manifest["config"]
    require(cfg["families"] == list(FAMILIES) and cfg["H_values"] == list(HORIZONS), "Wrong task grid")
    require(cfg["banks"]["final"] == BANK and cfg["final_n_per"] == N_PER, "Wrong final bank/count")
    require(cfg["world"] == {"plate_half": 0.01, "tray_height": 0.02}, "Unexpected world")
    require(cfg["source"] == {"kind": "procedural"} and cfg["judge_scale"] == 1.0, "Unexpected source/judge")
    tasks = TaskStore(out / "tasks", cfg, base)
    batches = []
    for mode, p in MODES:
        jobs = eval_jobs(tasks, cfg, ReconModel(), BANK, N_PER, p)
        for job in jobs:
            job.controller = "expert"
            require(job.real and job.recon == {"bias": {}, "corrections": {}}, "Wrong real/identity setting")
        for start in range(0, len(jobs), N_PER):
            batches.append((mode, jobs[start:start + N_PER]))
    task_refs = []
    for _, jobs in batches[:15]:
        for job in jobs:
            ref = job.tag["task_artifact"]
            identity = Path(ref["path"]).with_suffix(".identity.json")
            require(read_json(identity) == {"key": ref["key"], "sha256": ref["sha256"]}, "Bad task sidecar")
            task_refs.append({**ref, "identity_path": str(identity), "identity_sha256": file_hash(identity)})
    job_records = [{"mode": mode, **{k: v for k, v in asdict(job).items() if k != "task_payload"}}
                   for mode, jobs in batches for job in jobs]
    require(len(job_records) == 300 and len(task_refs) == 150, "Wrong evaluation count")
    inputs = {"schema_version": 1, "source_experiment_fingerprint": manifest["fingerprint"],
              "source_manifest": {"path": str(source / "experiment.json"), "sha256": file_hash(source / "experiment.json")},
              "main_protocol": {"path": str(parent / "PLAN.md"), "sha256": file_hash(parent / "PLAN.md")},
              "source_sha256": manifest["source_sha256"], "source_package_root": str(source / "source/src/horizon"),
              "script": {"path": str(Path(__file__).resolve()), "sha256": file_hash(__file__)},
              "tasks": task_refs, "jobs": job_records, "evaluation_bank": BANK, "tasks_per_cell": N_PER,
              "families": list(FAMILIES), "H_values": list(HORIZONS), "world": cfg["world"],
              "workers": WORKERS, "training_steps": 0, "calibration_attempts": 0,
              "expert_config": asdict(ExpertConfig()), "sim_config": asdict(SimConfig()),
              "scoring_tolerances": asdict(Tolerances()), "expert_privileged": True,
              "action_order": ["delta_x", "delta_y", "delta_z", "delta_yaw", "gripper"],
              "action_clip": [-1.0, 1.0], "rollout_max_steps": {str(H): H * 180 + 60 for H in HORIZONS},
              "done_patience": rollout.__kwdefaults__["done_patience"], "stop_when": "done",
              "scoring": "unchanged log.success = PredicateEngine.task_success on true final state"}
    plan = {**inputs, "fingerprint": digest(inputs)}
    definition_path = out / "definition.json"
    if definition_path.exists():
        require(read_json(definition_path) == plan, "Definition changed")
    else:
        require(not (out / "STARTED.json").exists(), "Started run has no definition")
        write_json(definition_path, plan)
    planned_text = plan_text(plan)
    plan_path = out / "PLAN_ADDENDUM.md"
    if plan_path.exists():
        require(plan_path.read_text(encoding="utf-8") == planned_text, "Saved plan changed")
    else:
        plan_path.write_text(planned_text, encoding="utf-8")
        write_json(out / "PLAN_CREATED.json", {"created_utc": utc_now(), "definition_fingerprint": plan["fingerprint"],
                                               "plan_sha256": file_hash(plan_path), "learned_outcomes_inspected": False})
    if args.plan_only:
        print(f"Planned exactly 300 episodes / 150 tasks: {plan['fingerprint']}", flush=True)
        return

    def verify_inputs():
        require(source_hashes() == plan["source_sha256"], "Frozen source changed")
        for ref in (plan["script"], plan["source_manifest"], plan["main_protocol"], *plan["tasks"]):
            require(file_hash(ref["path"]) == ref["sha256"], f"Input changed: {ref['path']}")
            if "identity_path" in ref:
                require(file_hash(ref["identity_path"]) == ref["identity_sha256"], "Task sidecar changed")

    verify_inputs()
    result_path = out / "results.json"
    if result_path.exists():
        saved = read_json(result_path)
        verify_saved(saved, plan)
        require((out / "EXPERT.md").read_text(encoding="utf-8") == report_text(saved), "Report changed")
        print("Existing 300-episode result verified; no new rollout.", flush=True)
        return
    with (out / "STARTED.json").open("x", encoding="utf-8") as handle:
        json.dump({"started_utc": utc_now(), "definition_fingerprint": plan["fingerprint"], "planned_episodes": 300}, handle)
    episodes, actions = [], {}
    started = time.perf_counter()
    with parallel.Runner(workers=WORKERS) as runner:
        for mode, jobs in batches:
            returned = runner.map(jobs)
            require(len(returned) == N_PER, "Worker result count differs")
            for r in returned:
                log = r.log
                action_key = f"{mode}_{r.job.family}_H{r.job.H}_s{r.job.task_seed}"
                final_sat = log.meta["final_sat"] if log is not None else None
                if log is not None:
                    actions[action_key] = log.action
                episodes.append({"mode": mode, "family": r.job.family, "H": r.job.H,
                                 "task_seed": r.job.task_seed, "rollout_seed": r.job.seed,
                                 "task_artifact": r.job.tag["task_artifact"], "error": r.error,
                                 "success": bool(log.success) if log is not None else None,
                                 "judged_success": bool(log.success_ver) if log is not None else None,
                                 "steps": log.steps if log is not None else None,
                                 "progress": float(np.mean(final_sat)) if log is not None else None,
                                 "final_satisfied": int(sum(final_sat)) if log is not None else None,
                                 "max_satisfied": max(int(sum(final_sat)), int(np.max(np.sum(log.sat_true, axis=1)))) if log is not None else None,
                                 "first_unsatisfied_index": next((i for i, sat in enumerate(final_sat) if not sat), len(final_sat)) if log is not None else None,
                                 "final_sat": final_sat, "final_held": log.meta["final_held"] if log is not None else None,
                                 "events": log.events if log is not None else None,
                                 "sim_steps": r.sim_steps, "worker_seconds": r.wall,
                                 "action_key": action_key if log is not None else None})
            write_json(out / "partial.json", {"definition_fingerprint": plan["fingerprint"], "episodes": episodes})
            print(f"{len(episodes)}/300: {mode} {jobs[0].family} H{jobs[0].H}: "
                  f"{sum(e['success'] is True for e in episodes[-N_PER:])}/{N_PER}", flush=True)
    pool_wall = time.perf_counter() - started
    verify_inputs()
    comparison = {"matched": 0, "unavailable": 0, "source": str(source / "tasks")}
    for ref in task_refs:
        other = source / "tasks" / Path(ref["path"]).name
        if other.is_file():
            require(file_hash(other) == ref["sha256"], f"Main-screen task differs: {other}")
            comparison["matched"] += 1
        else:
            comparison["unavailable"] += 1
    np.savez_compressed(out / "actions.npz", **actions)
    errors = sum(e["error"] is not None or e["success"] is None for e in episodes)
    require(Counter((e["mode"], e["family"], e["H"]) for e in episodes) ==
            Counter({(mode, family, H): N_PER for mode, _ in MODES for family in FAMILIES for H in HORIZONS}),
            "Wrong final result grid")
    result = {"schema_version": 1, "status": "complete" if not errors else "completed_with_errors",
              "definition_fingerprint": plan["fingerprint"], "completed_utc": utc_now(),
              "episodes": episodes, "summary": summarize(episodes), "main_task_comparison": comparison,
              "actions": {"path": str(out / "actions.npz"), "sha256": file_hash(out / "actions.npz")},
              "training_steps": 0, "calibration_attempts": 0,
              "runtime": {"python": sys.version, "executable": sys.executable, "platform": platform.platform(),
                          "numpy": np.__version__, "mujoco": mujoco.__version__, "workers": WORKERS},
              "ledger": {"episodes": len(episodes), "worker_errors": errors,
                         "control_steps": sum(e["steps"] or 0 for e in episodes),
                         "sim_steps": sum(e["sim_steps"] for e in episodes),
                         "worker_seconds": sum(e["worker_seconds"] for e in episodes),
                         "pool_wall_seconds": pool_wall,
                         "failed_worker_cost_may_be_unavailable": bool(errors)}}
    result["record_sha256"] = digest(result)
    verify_saved(result, plan)
    write_json(result_path, result)
    (out / "EXPERT.md").write_text(report_text(result), encoding="utf-8")
    print(f"Saved all 300 outcomes: {result_path}", flush=True)


if __name__ == "__main__":
    main()
